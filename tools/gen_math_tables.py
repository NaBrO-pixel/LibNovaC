#!/usr/bin/env python3
"""Generates src/math/tables.c: the constants libNovaC's <math.h> needs,
each stored as a double-double (hi + lo) exact to about 106 bits, computed
here with Python's decimal module at 80 digits. Pure Python, any host."""
import os
from decimal import Decimal as D, getcontext

getcontext().prec = 80
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")

def pi():
    # Machin: pi = 16 atan(1/5) - 4 atan(1/239)
    def atan_inv(n):
        x = D(1) / n; x2 = x * x; s = D(0); t = x; k = 1; sign = 1
        eps = D(10) ** -(getcontext().prec + 5)
        while True:
            term = t / k
            if term < eps: break
            s += sign * term; t *= x2; k += 2; sign = -sign
        return s
    return 16 * atan_inv(5) - 4 * atan_inv(239)

def atan(x):
    # reduce: atan(x) = 2 atan(x / (1 + sqrt(1 + x^2))), then the series
    x = D(x); halvings = 0
    while abs(x) > D("0.05"):
        x = x / (1 + (1 + x * x).sqrt()); halvings += 1
    s = D(0); t = x; k = 1; sign = 1; x2 = x * x
    while True:
        term = t / k
        if abs(term) < D(10) ** -85: break
        s += sign * term; t *= x2; k += 2; sign = -sign
    return s * (2 ** halvings)

def dd(v):
    hi = float(v)
    lo = float(v - D(hi))
    return hi, lo

def h(x):
    return x.hex() if x != 0 else "0.0"

PI = pi()
LN2 = D(2).ln()
out = []
w = out.append
w("/* Generated by tools/gen_math_tables.py - do not edit by hand. */")
w('#include "math_internal.h"\n')

w("/* 2^(j/64), j = 0..63 */")
w("const struct novac_dd novac__exp2_tab[64] = {")
for j in range(64):
    hi, lo = dd((D(j) / 64 * LN2).exp())
    w("    { %s, %s }," % (h(hi), h(lo)))
w("};\n")

w("/* log(m) reduction: for m in [1 + j/128, 1 + (j+1)/128), invc ~ 1/c_j and")
w(" * -log(invc) exactly as a double-double. */")
w("const double novac__log_invc[128] = {")
invcs = []
for j in range(128):
    c = 1 + (j + 0.5) / 128
    invc = float(D(1) / D(c))
    invcs.append(invc)
    w("    %s," % h(invc))
w("};")
w("const struct novac_dd novac__log_tab[128] = {")
for invc in invcs:
    hi, lo = dd(-D(invc).ln())
    w("    { %s, %s }," % (h(hi), h(lo)))
w("};\n")

w("/* atan(j/16), j = 0..64 */")
w("const struct novac_dd novac__atan_tab[65] = {")
for j in range(65):
    hi, lo = dd(atan(D(j) / 16))
    w("    { %s, %s }," % (h(hi), h(lo)))
w("};\n")

def const(name, v):
    hi, lo = dd(v)
    w("const struct novac_dd %s = { %s, %s };" % (name, h(hi), h(lo)))

const("novac__ln2", LN2)
const("novac__inv_ln2", 1 / LN2)
const("novac__inv_ln10", 1 / D(10).ln())
const("novac__log10_2", LN2 / D(10).ln())
const("novac__pi", PI)
const("novac__pi_2", PI / 2)
w("")

# 2/pi in binary, 64 bits per word, most significant first, for Payne-Hanek.
bits = 64 * 22
getcontext().prec = 500                   # 1,660 bits: comfortably more than the 1,408 kept
PI2 = pi()
v = int((2 / PI2) * (D(2) ** bits))
w("/* 2/pi = 0.b1 b2 b3 ... in binary; word i holds bits 64i+1 .. 64i+64. */")
w("const uint64_t novac__two_over_pi[22] = {")
for i in range(22):
    word = (v >> (bits - 64 * (i + 1))) & ((1 << 64) - 1)
    w("    0x%016xULL," % word)
w("};")

open(os.path.join(root, "src/math/tables.c"), "w").write("\n".join(out) + "\n")
print("ok")
