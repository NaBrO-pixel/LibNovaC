#!/usr/bin/env python3
"""Regenerates include/errno.h and src/string/strerror_table.h from the
Linux errno numbers and messages of the machine running it (Linux only).
The numbers are the x86-64 Linux ABI that NovarisOS implements."""
import errno, os, sys

if not sys.platform.startswith("linux"):
    sys.exit("run this on Linux: the values must be Linux's")

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
codes = {k: v for k, v in errno.errorcode.items() if k <= 133}
# Aliases Linux defines that errorcode maps to a single name.
names = dict(codes)
names[35] = "EDEADLK"

with open(os.path.join(root, "include/errno.h"), "w") as f:
    f.write("""/* Generated by tools/gen_errno.py - do not edit by hand. */
#ifndef NOVAC_ERRNO_H
#define NOVAC_ERRNO_H
#include <novac/defs.h>

NOVAC_BEGIN_DECLS
/* Returns the address of the error variable. Single global today; will become
 * per-thread once NovarisOS exposes thread-local storage. */
int *__novac_errno_location(void);
NOVAC_END_DECLS

#define errno (*__novac_errno_location())

/* libNovaC's error numbers ARE the Linux x86-64 values, because that is the
 * ABI NovarisOS implements: the kernel returns -errno and the syscall layer
 * stores the same number unchanged. */
""")
    for k in sorted(names):
        f.write("#define %-16s %d\n" % (names[k], k))
    f.write("""#define EWOULDBLOCK      EAGAIN
#define EDEADLOCK        EDEADLK
#define EOPNOTSUPP       ENOTSUP

#endif
""")

with open(os.path.join(root, "src/string/strerror_table.h"), "w") as f:
    f.write("/* Generated by tools/gen_errno.py - do not edit by hand. */\n")
    f.write("static const char *const novac_errmsg[] = {\n")
    f.write('    [0] = "Success",\n')
    for k in sorted(names):
        f.write('    [%s] = "%s",\n' % (names[k], os.strerror(k)))
    f.write("};\n")
