#!/usr/bin/env python3
"""Regenerates tests/host/rename.h: one #define per function libNovaC's
public headers declare, so the host unit tests can link libNovaC's portable
core next to the host libc without the two colliding. Run after adding a
public function."""
import os, re

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
inc = os.path.join(root, "include")
skip = {"sizeof", "defined", "return", "if", "while", "for", "switch", "typeof",
        "main", "int", "void", "char", "long", "short", "unsigned", "double", "float",
        "signed", "const", "struct", "union", "va_start", "va_end", "va_arg", "va_copy", "offsetof", "assert"}
names = set()
for dirpath, _, files in os.walk(inc):
    for fn in files:
        if not fn.endswith(".h"):
            continue
        text = open(os.path.join(dirpath, fn)).read()
        text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
        for m in re.finditer(r"NOVAC_MATH_[12]\((\w+)\)", text):   # macro-declared math
            if m.group(1) != "n":
                names.update({m.group(1), m.group(1) + "f", m.group(1) + "l"})
        for line in text.split("\n"):
            if line.lstrip().startswith("#"):
                continue
            for m in re.finditer(r"(?:^|[\s\*])([A-Za-z_][A-Za-z0-9_]*)\s*\((?!\s*\*)", line):
                n = m.group(1)
                if n.startswith("__") or n.startswith("NOVAC_") or n in skip:
                    continue
                if n.startswith("novac_"):            # libNovaC's own namespace: no clash
                    continue
                names.add(n)
types = ["div_t", "ldiv_t", "lldiv_t", "imaxdiv_t"]
with open(os.path.join(root, "tests/host/rename.h"), "w") as f:
    f.write("""/* Generated by tools/gen_rename.py - do not edit by hand.
 *
 * HOST TESTS ONLY. Force-included into library and test translation units so
 * libNovaC's public symbols (memcpy, malloc, ...) are renamed and cannot
 * collide with the host libc linked into the test runner. Never used for the
 * NovarisOS target build. */
#ifndef NOVAC_HOST_RENAME_H
#define NOVAC_HOST_RENAME_H
""")
    for n in sorted(names) + types:
        f.write("#define %s novact_%s\n" % (n, n))
    f.write("#endif\n")
print(len(names), "functions")
